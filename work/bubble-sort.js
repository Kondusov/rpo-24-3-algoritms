// Пузырьковая сортировка (Bubble Sort) — это простой алгоритм, который многократно проходит по массиву, сравнивает соседние элементы и меняет их местами, если они стоят в неправильном порядке. За каждый проход самый большой элемент «всплывает» в конец массива, как пузырек воздуха в воде.

// Как это работает по шагам

// 1. Берем первые два элемента массива. Если первый больше второго — меняем их местами.
// 2. Сдвигаемся на один элемент вправо и повторяем сравнение.
// 3. Доходим до конца массива. Теперь на последнем месте гарантированно стоит максимальное число.
// 4. Повторяем процесс для оставшейся части массива (без уже отсортированных элементов в конце), пока перестановки не прекратятся.
// Пример кода на JavaScript
// Ниже приведена оптимизированная версия алгоритма с флагом swapped — она прерывает работу досрочно, если массив уже отсортирован.

function bubbleSort(arr) {
  const n = arr.length;
  let swapped;
  for (let i = 0; i < n - 1; i++) {
    console.log('Итерация i номер - ' + i);
    swapped = false;
    // С каждым проходом последние i элементов уже на своих местах
    for (let j = 0; j < n - 1 - i; j++) {
        console.log('Итерация j - ' + j);
      if (arr[j] > arr[j + 1]) {
          console.log('Заменили - '+ arr[j]+' на '+ arr[j + 1]);
        // Меняем элементы местами с помощью деструктуризации
        // [arr[j], arr[j + 1]] = [arr[j + 1], arr[j]]; // множественная замена
        temp = arr[j]; arr[j] = arr[j+1]; arr[j+1] = temp; 
        swapped = true;
      }
    }
    // Если за весь проход не было ни одного обмена, массив отсортирован
    if (!swapped) break;
  }
  return arr;
}
const numbers = [5,4,9,2,3,8];
console.log(bubbleSort(numbers)); // [2, 3, 4, 5, 8]


